export function getTipsForDomains(
  domains: string[],
  childName: string,
  language: 'en' | 'hi',
  maxTips = 3,
): Array<{ tipText: string; linkedGoalName?: string }> {
  const matched = domains
    .map((d) => tips.find((t) => t.domain === d))
    .filter((t): t is ParentTip => !!t)
    .slice(0, maxTips);

  return matched.map((t) => ({
    tipText: t[language].replace(/\{\{childName\}\}/g, childName),
  }));
}

export default tips;
